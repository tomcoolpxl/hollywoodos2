/**
 * Projects [lon, lat] (-180..180, -90..90) onto a 2D equirectangular viewport.
 */
export function projectEquirectangular(lon, lat, width, height) {
    const x = ((lon + 180) / 360) * width;
    const y = ((90 - lat) / 180) * height;
    return { x, y };
}
